#!/usr/bin/env bash
# Generates docs/api/ (the Markdown reference of the public API of the five library crates) from
# rustdoc JSON, with tools/api-docs.
#   scripts/gen-api-docs.sh          write docs/api/
#   scripts/gen-api-docs.sh --check  fail (exit 1, with a diff) when docs/api/ is stale
# Exit 2 on a setup error (a tool or build failed) or when the tool's completeness checks fail
# (it prints each finding): a rustdoc JSON format the pinned `rustdoc-types` does not read, a
# public item no page shows, a set of items that differs from rustdoc's own all.html. Output is
# byte-stable: no dates, no absolute paths, everything sorted.
#
# The JSON needs the nightly flag `--output-format json`; the toolchain is pinned stable, so this
# sets RUSTC_BOOTSTRAP=1 for the rustdoc runs only (D287). A toolchain bump that moves the JSON
# format makes the tool exit 2 until the `rustdoc-types` pin in tools/api-docs/Cargo.toml moves.
# bash 3.2 / BSD safe.
set -euo pipefail
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# API_DIR lets tests run against a temp copy; default is the real reference.
API="${API_DIR:-$ROOT/docs/api}"
TARGET="$ROOT/target/api-docs"
PACKAGES="lune-ui-core lune-ui-wgpu lune-ui-winit lune-ui-platform lune-ui"

mode=write
case "${1:-}" in
  '') ;;
  --check) mode=check ;;
  *) echo "usage: gen-api-docs.sh [--check]" >&2; exit 2 ;;
esac

for tool in cargo diff; do
  command -v "$tool" > /dev/null 2>&1 || { echo "gen-api-docs: '$tool' is not installed" >&2; exit 2; }
done

TMP="$(mktemp -d "${TMPDIR:-/tmp}/gen-api-docs.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT
cd "$ROOT"

# run <log name> <command...>: runs quietly, shows the log only on failure. The rustdoc flags of
# the caller's environment are dropped so the output does not depend on them.
run() {
  local name="$1"; shift
  if ! env -u RUSTDOCFLAGS -u CARGO_ENCODED_RUSTDOCFLAGS "$@" > "$TMP/$name.log" 2>&1; then
    cat "$TMP/$name.log" >&2
    echo "gen-api-docs: '$name' failed" >&2
    exit 2
  fi
}

for p in $PACKAGES; do
  run "rustdoc-$p" env RUSTC_BOOTSTRAP=1 CARGO_TARGET_DIR="$TARGET" \
    cargo rustdoc -p "$p" --lib --all-features -- -Z unstable-options --output-format json
done
pargs=""
for p in $PACKAGES; do pargs="$pargs -p $p"; done
# shellcheck disable=SC2086
run "doc" env CARGO_TARGET_DIR="$TARGET" cargo doc --no-deps --all-features $pargs

rc=0
cargo run -q -p api-docs -- --json-dir "$TARGET/doc" --html-dir "$TARGET/doc" --out "$TMP/api" || rc=$?
if [ "$rc" -ne 0 ]; then
  echo "gen-api-docs: the generator failed (exit $rc)" >&2
  exit 2
fi
files="$(find "$TMP/api" -type f | wc -l | tr -d ' ')"

if [ "$mode" = check ]; then
  if [ ! -d "$API" ]; then echo "gen-api-docs: ${API#"$ROOT"/} is missing; run scripts/gen-api-docs.sh" >&2; exit 1; fi
  if ! diff -ru "$API" "$TMP/api" > "$TMP/diff"; then
    cat "$TMP/diff" >&2
    echo "gen-api-docs: ${API#"$ROOT"/} is stale; run scripts/gen-api-docs.sh" >&2
    exit 1
  fi
  echo "gen-api-docs: up to date"
else
  # Replace only a directory this script made (its index carries the generated banner).
  if [ -e "$API" ] && ! grep -q 'generated by scripts/gen-api-docs.sh' "$API/INDEX.md" 2> /dev/null; then
    echo "gen-api-docs: ${API#"$ROOT"/} exists and is not generated output; not replacing it" >&2
    exit 2
  fi
  rm -rf "$API"
  mkdir -p "$(dirname "$API")"
  cp -R "$TMP/api" "$API"
  echo "gen-api-docs: wrote ${API#"$ROOT"/} ($files files)"
fi
