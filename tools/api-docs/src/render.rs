//! Writing the pages, and counting what was written against what the JSON holds.

use std::collections::{BTreeMap, HashMap, HashSet};
use std::fmt::Write;

use rustdoc_types::{Item, ItemEnum, Visibility};

use crate::docs;
use crate::plan::{Members, Page, PageKey, Placed, Plan, Row, variant_fields};
use crate::sig;
use crate::view::{KIND_ORDER, Kind};
use crate::world::{CRATES, FACADE, ItemRef, Res, World};

const BANNER: &str = "<!-- generated by scripts/gen-api-docs.sh - do not edit -->";

/// What was written and what was left out, by crate.
#[derive(Default)]
pub(crate) struct Counts {
    /// (crate, class) -> how many; the classes are the named skips.
    pub(crate) skipped: BTreeMap<(usize, &'static str), u32>,
}

pub(crate) struct Rendered {
    /// Relative path under `docs/api/` -> file text.
    pub(crate) files: BTreeMap<String, String>,
    pub(crate) counts: Counts,
    /// Everything that failed to render or to check; empty when the output is complete.
    pub(crate) problems: Vec<String>,
}

struct Renderer<'a> {
    w: &'a World,
    plan: &'a Plan,
    /// How many times each item was written.
    rendered: HashMap<ItemRef, u32>,
    /// Items that are required because a rendered parent holds them.
    expected: HashSet<ItemRef>,
    /// Items left out on purpose, with their class.
    skipped: HashMap<ItemRef, &'static str>,
    counts: Counts,
    problems: Vec<String>,
}

macro_rules! put {
    ($out:expr) => {{ let _ = writeln!($out); }};
    ($out:expr, $($arg:tt)*) => {{ let _ = writeln!($out, $($arg)*); }};
}

/// The file of a page, relative to `docs/api/`.
pub(crate) fn page_file(w: &World, key: &PageKey) -> String {
    let dir = w.crates[key.0].dir;
    if key.1.is_empty() {
        format!("{dir}/index.md")
    } else {
        format!("{dir}/{}.md", key.1.join("/"))
    }
}

/// The relative link from file `from` to file `to`, both relative to `docs/api/`.
pub(crate) fn rel(from: &str, to: &str) -> String {
    let f: Vec<&str> = from.split('/').collect();
    let t: Vec<&str> = to.split('/').collect();
    let f_dir = &f[..f.len() - 1];
    let common = f_dir
        .iter()
        .zip(t.iter())
        .take_while(|(a, b)| a == b)
        .count();
    let mut parts: Vec<&str> = vec![".."; f_dir.len() - common];
    parts.extend(&t[common..]);
    parts.join("/")
}

pub(crate) fn render(w: &World, plan: &Plan) -> Res<Rendered> {
    let mut r = Renderer {
        w,
        plan,
        rendered: HashMap::new(),
        expected: HashSet::new(),
        skipped: HashMap::new(),
        counts: Counts::default(),
        problems: Vec::new(),
    };
    let mut files = BTreeMap::new();
    for (key, page) in &plan.pages {
        let file = page_file(w, key);
        let text = r.page(key, page, &file)?;
        if files.insert(file.clone(), text).is_some() {
            r.problems.push(format!("two pages want the file {file}"));
        }
    }
    r.check_complete();
    let index = r.index_md();
    files.insert("INDEX.md".to_string(), index);
    Ok(Rendered {
        files,
        counts: r.counts,
        problems: r.problems,
    })
}

impl Renderer<'_> {
    fn mark(&mut self, r: ItemRef) {
        *self.rendered.entry(r).or_insert(0) += 1;
    }

    fn skip(&mut self, r: ItemRef, class: &'static str) {
        self.expected.insert(r);
        self.skipped.insert(r, class);
        *self.counts.skipped.entry((r.0, class)).or_insert(0) += 1;
    }

    fn url(&self, from: &str, r: ItemRef) -> Option<String> {
        let (key, anchor) = self.plan.anchors.get(&r)?;
        let to = page_file(self.w, key);
        let base = rel(from, &to);
        Some(if anchor.is_empty() {
            base
        } else {
            format!("{base}#{anchor}")
        })
    }

    /// The doc comment of `it` (an item of crate `cn`) with links to this reference and its
    /// headings moved down by `by`.
    fn docs_of(&self, it: &Item, cn: usize, from: &str, by: usize) -> String {
        let Some(d) = &it.docs else {
            return String::new();
        };
        let resolve = |key: &str| {
            let id = it.links.get(key)?;
            let target = self.w.locate(cn, *id)?;
            self.url(from, target)
        };
        docs::demote(&docs::rewrite_links(d, &resolve), by)
    }

    fn summary_of(&self, it: &Item, cn: usize, from: &str) -> String {
        let Some(d) = &it.docs else {
            return String::new();
        };
        let resolve = |key: &str| {
            let id = it.links.get(key)?;
            let target = self.w.locate(cn, *id)?;
            self.url(from, target)
        };
        docs::summary(&docs::rewrite_links(d, &resolve))
    }

    fn source_line(&mut self, it: &Item, cn: usize) -> Option<String> {
        let span = it.span.as_ref()?;
        if span.filename.is_absolute() {
            self.problems.push(format!(
                "{}: the span of {} is an absolute path ({}); the reference keeps paths relative",
                self.w.crates[cn].lib,
                it.name.as_deref().unwrap_or("?"),
                span.filename.display()
            ));
            return None;
        }
        let f = span.filename.to_string_lossy().replace('\\', "/");
        Some(format!("Source: `{f}:{}`", span.begin.0))
    }

    fn page(&mut self, key: &PageKey, page: &Page, file: &str) -> Res<String> {
        let cn = key.0;
        let lib = self.w.crates[cn].lib;
        let module_item = self.w.item(page.module)?;
        self.mark(page.module);
        let mut path = vec![lib.to_string()];
        path.extend(key.1.iter().cloned());
        let full = path.join("::");
        let mut out = String::new();
        put!(out, "{BANNER}");
        put!(out);
        let what = if key.1.is_empty() { "Crate" } else { "Module" };
        put!(out, "# {what} `{full}`");
        put!(out);
        put!(
            out,
            "[API reference]({}){}",
            rel(file, "INDEX.md"),
            self.parent_link(key, file)
        );
        put!(out);
        let d = self.docs_of(module_item, cn, file, 2);
        if !d.is_empty() {
            put!(out, "{}", d.trim_end());
            put!(out);
        }
        if let Some(s) = self.source_line(module_item, cn) {
            put!(out, "{s}");
            put!(out);
        }
        if !page.submodules.is_empty() {
            put!(out, "## Modules");
            put!(out);
            for name in &page.submodules {
                let mut ck = key.clone();
                ck.1.push(name.clone());
                let child_file = page_file(self.w, &ck);
                let summary = match self.plan.pages.get(&ck) {
                    Some(p) => self.summary_of(self.w.item(p.module)?, cn, file),
                    None => String::new(),
                };
                let tail = if summary.is_empty() {
                    String::new()
                } else {
                    format!(" - {summary}")
                };
                put!(out, "- [`{name}`]({}){tail}", rel(file, &child_file));
            }
            put!(out);
        }
        for kind in KIND_ORDER {
            if kind == Kind::Module {
                continue;
            }
            let group: Vec<&Placed> = page.body.iter().filter(|p| p.kind == kind).collect();
            if group.is_empty() {
                continue;
            }
            put!(out, "## {}", kind.plural());
            put!(out);
            for p in group {
                self.item(&mut out, file, p)?;
            }
        }
        for u in &page.uses {
            self.mark(*u);
        }
        if !page.rows.is_empty() {
            put!(out, "## Re-exports");
            put!(out);
            put!(out, "| Name | Kind | Defined at |");
            put!(out, "| --- | --- | --- |");
            for row in &page.rows {
                let line = self.row(file, row);
                put!(out, "{line}");
            }
            put!(out);
        }
        Ok(out)
    }

    fn parent_link(&self, key: &PageKey, file: &str) -> String {
        if key.1.is_empty() {
            return String::new();
        }
        let mut pk = key.clone();
        pk.1.pop();
        let pf = page_file(self.w, &pk);
        let name = if pk.1.is_empty() {
            self.w.crates[pk.0].lib.to_string()
        } else {
            format!("{}::{}", self.w.crates[pk.0].lib, pk.1.join("::"))
        };
        format!(" / parent [`{name}`]({})", rel(file, &pf))
    }

    fn row(&mut self, file: &str, row: &Row) -> String {
        let canon = self
            .canonical_path(row.target)
            .unwrap_or_else(|| row.name.clone());
        let link = match self.url(file, row.target) {
            Some(u) => format!("[`{canon}`]({u})"),
            None => {
                self.problems.push(format!(
                    "{file}: the re-export {} points at {canon}, which no page documents",
                    row.name
                ));
                format!("`{canon}`")
            }
        };
        format!("| `{}` | {} | {link} |", row.name, row.kind.word())
    }

    /// `lune_ui_core::backdrop::Material`, from rustdoc's own path table.
    fn canonical_path(&self, r: ItemRef) -> Option<String> {
        let s = self.w.crates[r.0].data.paths.get(&r.1)?;
        Some(s.path.join("::"))
    }

    fn item(&mut self, out: &mut String, file: &str, p: &Placed) -> Res<()> {
        let cn = p.item.0;
        let it = self.w.item(p.item)?;
        self.mark(p.item);
        let anchor = self
            .plan
            .anchors
            .get(&p.item)
            .map(|(_, a)| a.clone())
            .unwrap_or_default();
        put!(out, "<a id=\"{anchor}\"></a>");
        put!(out, "### {} `{}`", p.kind.word(), p.name);
        put!(out);
        if let Some(dep) = &it.deprecation {
            let since = dep
                .since
                .as_ref()
                .map(|s| format!(" since {s}"))
                .unwrap_or_default();
            let note = dep
                .note
                .as_ref()
                .map(|n| format!(": {n}"))
                .unwrap_or_default();
            put!(out, "**Deprecated**{since}{note}");
            put!(out);
        }
        self.signature_block(out, cn, it, &p.name)?;
        let d = self.docs_of(it, cn, file, 3);
        if !d.is_empty() {
            put!(out, "{}", d.trim_end());
            put!(out);
        }
        if let Some(s) = self.source_line(it, cn) {
            put!(out, "{s}");
            put!(out);
        }
        let empty = Members::default();
        let m = self.plan.members.get(&p.item).unwrap_or(&empty);
        self.members(out, file, cn, m)?;
        Ok(())
    }

    fn signature_block(&mut self, out: &mut String, cn: usize, it: &Item, name: &str) -> Res<()> {
        let sig = sig::signature(self.w, cn, it, name)?;
        // The attributes sit inside the block, above the signature.
        let attrs = sig::attrs(&it.attrs);
        put!(out, "```rust");
        for a in attrs {
            put!(out, "{a}");
        }
        put!(out, "{sig}");
        put!(out, "```");
        put!(out);
        Ok(())
    }

    #[allow(clippy::too_many_lines)]
    fn members(&mut self, out: &mut String, file: &str, cn: usize, m: &Members) -> Res<()> {
        if !m.fields.is_empty() {
            put!(out, "**Fields**");
            put!(out);
            for f in &m.fields {
                self.member(out, file, cn, *f, 0, &m.fields)?;
            }
        }
        if !m.variants.is_empty() {
            put!(out, "**Variants**");
            put!(out);
            for v in &m.variants {
                self.member(out, file, cn, *v, 0, &m.variants)?;
                // The variant's signature shows its fields; one is listed again only when it has
                // docs of its own.
                let fields = variant_fields(self.w, *v)?;
                for f in &fields {
                    if self.w.item(*f)?.docs.is_some() {
                        self.member(out, file, cn, *f, 4, &fields)?;
                    } else {
                        self.mark(*f);
                        self.expected.insert(*f);
                    }
                }
            }
        }
        if !m.trait_items.is_empty() {
            let mut required = Vec::new();
            let mut provided = Vec::new();
            for i in &m.trait_items {
                self.expected.insert(*i);
                let it = self.w.item(*i)?;
                let has_default = match &it.inner {
                    ItemEnum::Function(f) => f.has_body,
                    ItemEnum::AssocConst { value, .. } => value.is_some(),
                    ItemEnum::AssocType { type_, .. } => type_.is_some(),
                    ItemEnum::Module(_)
                    | ItemEnum::ExternCrate { .. }
                    | ItemEnum::Use(_)
                    | ItemEnum::Union(_)
                    | ItemEnum::Struct(_)
                    | ItemEnum::StructField(_)
                    | ItemEnum::Enum(_)
                    | ItemEnum::Variant(_)
                    | ItemEnum::Trait(_)
                    | ItemEnum::TraitAlias(_)
                    | ItemEnum::Impl(_)
                    | ItemEnum::TypeAlias(_)
                    | ItemEnum::Constant { .. }
                    | ItemEnum::Static(_)
                    | ItemEnum::ExternType
                    | ItemEnum::Macro(_)
                    | ItemEnum::ProcMacro(_)
                    | ItemEnum::Primitive(_) => false,
                };
                let rank = match &it.inner {
                    ItemEnum::AssocType { .. } => 0,
                    ItemEnum::AssocConst { .. } => 1,
                    _ => 2,
                };
                let entry = (rank, crate::plan::name_of(it).to_string(), *i);
                if has_default {
                    provided.push(entry)
                } else {
                    required.push(entry)
                }
            }
            for (label, mut list) in [("Required items", required), ("Provided items", provided)] {
                if list.is_empty() {
                    continue;
                }
                list.sort();
                put!(out, "**{label}**");
                put!(out);
                for (_, _, i) in list {
                    self.member(out, file, cn, i, 0, &[])?;
                }
            }
        }
        if !m.inherent.is_empty() {
            let mut blocks: Vec<(String, &ItemRef, &Vec<ItemRef>)> = Vec::new();
            for (imp, items) in &m.inherent {
                let ItemEnum::Impl(i) = &self.w.item(*imp)?.inner else {
                    continue;
                };
                blocks.push((sig::impl_header(i, true), imp, items));
            }
            blocks.sort_by(|a, b| a.0.cmp(&b.0));
            put!(out, "**Methods and associated items**");
            put!(out);
            for (header, imp, items) in blocks {
                self.mark(*imp);
                self.expected.insert(*imp);
                put!(out, "`{header}`");
                put!(out);
                for i in items {
                    self.member(out, file, cn, *i, 0, &[])?;
                }
            }
        }
        if !m.trait_impls.is_empty() || !m.implementors.is_empty() {
            let mut lines = Vec::new();
            for r in &m.trait_impls {
                lines.push(self.impl_line(*r)?);
            }
            if !lines.is_empty() {
                lines.sort();
                put!(out, "**Trait implementations**");
                put!(out);
                for l in lines {
                    put!(out, "- `{l}`");
                }
                put!(out);
            }
            let mut lines = Vec::new();
            for r in &m.implementors {
                lines.push(self.impl_line(*r)?);
            }
            if !lines.is_empty() {
                lines.sort();
                put!(out, "**Implementors on other types**");
                put!(out);
                for l in lines {
                    put!(out, "- `{l}`");
                }
                put!(out);
            }
        }
        for (r, class) in &m.skipped_impls {
            self.skip(*r, class);
            if let ItemEnum::Impl(i) = &self.w.item(*r)?.inner {
                for id in &i.items {
                    self.skip((r.0, *id), "items of the omitted impls");
                }
            }
        }
        Ok(())
    }

    /// Writes one impl as a line: marks the impl, leaves its items out (named class).
    fn impl_line(&mut self, r: ItemRef) -> Res<String> {
        let it = self.w.item(r)?;
        let ItemEnum::Impl(i) = &it.inner else {
            return Ok(String::new());
        };
        self.mark(r);
        self.expected.insert(r);
        for id in &i.items {
            self.skip((r.0, *id), "items of the trait impls shown as one line");
        }
        Ok(sig::impl_header(i, true))
    }

    /// One field, variant or associated item as a list entry; `pad` is the nesting in spaces.
    fn member(
        &mut self,
        out: &mut String,
        file: &str,
        cn: usize,
        r: ItemRef,
        pad: usize,
        siblings: &[ItemRef],
    ) -> Res<()> {
        self.mark(r);
        self.expected.insert(r);
        let it = self.w.item(r)?;
        let name = match &it.name {
            Some(n) => n.clone(),
            None => crate::plan::field_name(self.w, r, siblings)?,
        };
        let sig_text = sig::signature(self.w, cn, it, &name)?;
        let anchor = self.plan.anchors.get(&r).map(|(_, a)| a.clone());
        let pad_s = " ".repeat(pad);
        let a = anchor
            .map(|a| format!("<a id=\"{a}\"></a>"))
            .unwrap_or_default();
        if sig_text.contains('\n') {
            put!(out, "{pad_s}- {a}");
            put!(out);
            put!(out, "{pad_s}  ```rust");
            put!(out, "{}", docs::indent(&sig_text, pad + 2).trim_end());
            put!(out, "{pad_s}  ```");
        } else {
            put!(out, "{pad_s}- {a}`{sig_text}`");
        }
        for a in sig::attrs(&it.attrs) {
            put!(out, "{pad_s}  `{a}`");
        }
        let d = self.docs_of(it, cn, file, 5);
        if !d.is_empty() {
            put!(out);
            put!(out, "{}", docs::indent(d.trim_end(), pad + 2));
        }
        put!(out);
        Ok(())
    }

    /// Check (a): every item the JSON holds that the reference must show was written once, or is
    /// in a named skip class.
    fn check_complete(&mut self) {
        for (ci, k) in self.w.crates.iter().enumerate() {
            let mut bad: Vec<String> = Vec::new();
            for (id, it) in &k.data.index {
                if it.crate_id != 0 {
                    continue;
                }
                let r = (ci, *id);
                let required = matches!(it.visibility, Visibility::Public)
                    || self.expected.contains(&r)
                    || matches!(it.inner, ItemEnum::Impl(_));
                if !required || self.skipped.contains_key(&r) {
                    continue;
                }
                let n = self.rendered.get(&r).copied().unwrap_or(0);
                if n != 1 {
                    let where_ = it
                        .span
                        .as_ref()
                        .map(|s| format!("{}:{}", s.filename.display(), s.begin.0))
                        .unwrap_or_default();
                    bad.push(format!(
                        "{}: {} `{}` ({where_}) was written {n} times, expected once",
                        k.lib,
                        inner_word(&it.inner),
                        it.name.as_deref().unwrap_or("?")
                    ));
                }
            }
            bad.sort();
            self.problems.extend(bad);
        }
    }

    fn index_md(&self) -> String {
        let mut out = String::new();
        put!(out, "# API reference");
        put!(out);
        put!(out, "{BANNER}");
        put!(out);
        put!(
            out,
            "Generated by `scripts/gen-api-docs.sh` - do not edit. Regenerate with `scripts/gen-api-docs.sh`; the gate runs `scripts/gen-api-docs.sh --check`."
        );
        put!(out);
        put!(
            out,
            "The public API of the five library crates (`lune-ui-core`, `lune-ui-wgpu`, `lune-ui-winit`, `lune-ui-platform` and the facade `lune-ui`), from rustdoc JSON of the macOS build with `--all-features`. The pages of `lune-ui-platform` and `lune-ui-winit` generated from the `x86_64-pc-windows-msvc` build were identical to these (D287), so the OS surface is the same on both. Component descriptions, status and consumers: [docs/components/INDEX.md](../components/INDEX.md)."
        );
        put!(out);
        put!(
            out,
            "Each crate has a page per module (`<crate>/<module path>.md`; the root is `index.md`). An item has its signature, its doc comment and its source line; a type lists its fields or variants, its methods and its trait implementations. Synthetic and blanket implementations (and the items of the impls shown as one line) are left out and counted. The facade `lune-ui` re-exports the other four: its pages are tables that link to the page that documents each item."
        );
        put!(out);
        put!(out, "## Crates");
        put!(out);
        for (ci, (dir, lib)) in CRATES.iter().enumerate() {
            let pages: Vec<(&PageKey, &Page)> =
                self.plan.pages.iter().filter(|(k, _)| k.0 == ci).collect();
            let items: usize = pages.iter().map(|(_, p)| p.body.len()).sum();
            let rows: usize = pages.iter().map(|(_, p)| p.rows.len()).sum();
            put!(out, "### `{dir}` (`{lib}`)");
            put!(out);
            let mut line = if ci == FACADE {
                format!("{} modules, {rows} re-exports shown as links.", pages.len())
            } else {
                format!("{} modules, {items} items.", pages.len())
            };
            let omitted: Vec<String> = self
                .counts
                .skipped
                .iter()
                .filter(|((c, _), _)| *c == ci)
                .map(|((_, class), n)| format!("{n} {class}"))
                .collect();
            if !omitted.is_empty() {
                line.push_str(&format!(" Left out and counted: {}.", omitted.join(", ")));
            }
            put!(out, "{line}");
            put!(out);
            put!(
                out,
                "| Module | {} |",
                if ci == FACADE { "Re-exports" } else { "Items" }
            );
            put!(out, "| --- | --- |");
            for (k, p) in pages {
                let name = if k.1.is_empty() {
                    (*lib).to_string()
                } else {
                    format!("{lib}::{}", k.1.join("::"))
                };
                let n = if ci == FACADE {
                    p.rows.len()
                } else {
                    p.body.len()
                };
                put!(
                    out,
                    "| [`{name}`]({}) | {n} |",
                    rel("INDEX.md", &page_file(self.w, k))
                );
            }
            put!(out);
        }
        put!(out, "## All items, A to Z");
        put!(out);
        put!(
            out,
            "Every top-level item of the four owning crates, by name."
        );
        put!(out);
        let mut all: Vec<(String, String, &Placed, PageKey)> = Vec::new();
        for (k, p) in &self.plan.pages {
            if k.0 == FACADE {
                continue;
            }
            for item in &p.body {
                all.push((item.name.to_lowercase(), item.name.clone(), item, k.clone()));
            }
        }
        all.sort_by(|a, b| {
            (&a.0, &a.1, a.3.0, &a.3.1, a.2.kind).cmp(&(&b.0, &b.1, b.3.0, &b.3.1, b.2.kind))
        });
        for (_, name, item, k) in all {
            let anchor = self
                .plan
                .anchors
                .get(&item.item)
                .map(|(_, a)| a.as_str())
                .unwrap_or("");
            let mut path = vec![self.w.crates[k.0].lib.to_string()];
            path.extend(k.1.iter().cloned());
            put!(
                out,
                "- [`{name}`]({}#{anchor}) - {}, `{}`",
                rel("INDEX.md", &page_file(self.w, &k)),
                item.kind.word().to_lowercase(),
                path.join("::")
            );
        }
        out
    }
}

fn inner_word(inner: &ItemEnum) -> &'static str {
    match inner {
        ItemEnum::Module(_) => "module",
        ItemEnum::ExternCrate { .. } => "extern crate",
        ItemEnum::Use(_) => "re-export",
        ItemEnum::Union(_) => "union",
        ItemEnum::Struct(_) => "struct",
        ItemEnum::StructField(_) => "field",
        ItemEnum::Enum(_) => "enum",
        ItemEnum::Variant(_) => "variant",
        ItemEnum::Function(_) => "function",
        ItemEnum::Trait(_) => "trait",
        ItemEnum::TraitAlias(_) => "trait alias",
        ItemEnum::Impl(_) => "impl",
        ItemEnum::TypeAlias(_) => "type alias",
        ItemEnum::Constant { .. } => "constant",
        ItemEnum::Static(_) => "static",
        ItemEnum::ExternType => "extern type",
        ItemEnum::Macro(_) => "macro",
        ItemEnum::ProcMacro(_) => "proc macro",
        ItemEnum::Primitive(_) => "primitive",
        ItemEnum::AssocConst { .. } => "associated constant",
        ItemEnum::AssocType { .. } => "associated type",
    }
}
